// Turns the hands in Michelangelo's "Creation of Adam" (public domain) into ASCII.
// Source: https://commons.wikimedia.org/wiki/File:Creation_of_Adam_(Michelangelo)_Detail.jpg
// Usage: node scripts/make-ascii-hands.mjs <path-to-detail.jpg> [cols]
// Writes src/components/ascii-hands-data.ts with two versions:
//   HANDS_DARK  for black backgrounds (lit skin = dense characters)
//   HANDS_LIGHT for white backgrounds (shadowed skin = dense characters)
import sharp from "sharp";
import { writeFileSync } from "node:fs";

const [, , src, colsArg] = process.argv;
if (!src) throw new Error("pass the path to the source image");
const COLS = Number(colsArg) || 300;
const CHAR_ASPECT = 0.5; // monospace cells are about twice as tall as wide
const RAMP = " .,:;-~=+*xoO#%@"; // light to dense
const WARM_MIN = 18; // plaster scores ~10-12 on warmth (r - b), skin 23-51

// Crop to the band with both hands, dropping the knee and sky
const meta = await sharp(src).metadata();
const crop = { left: 0, top: Math.round(meta.height * 0.2), width: Math.round(meta.width * 0.96), // 0.96 drops the red cloth at the right edge
  height: Math.round(meta.height * 0.38) };
const rows = Math.round(((COLS * crop.height) / crop.width) * CHAR_ASPECT);
const { data, info } = await sharp(src)
  .extract(crop)
  .median(5) // clears small warm specks in the plaster
  .resize(COLS, rows, { fit: "fill", kernel: "lanczos3" })
  .sharpen({ sigma: 1 })
  .removeAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });

// Skin mask and brightness per cell
const W = info.width, H = info.height;
const lum = new Float32Array(W * H), mask = new Float32Array(W * H);
for (let p = 0; p < W * H; p++) {
  const r = data[p * 3], g = data[p * 3 + 1], b = data[p * 3 + 2];
  lum[p] = (0.299 * r + 0.587 * g + 0.114 * b) / 255;
  mask[p] = Math.max(0, Math.min(1, (r - b - WARM_MIN) / 12));
}

// Stretch contrast across skin only, so the hands use the whole character ramp
const skin = [...lum].filter((_, p) => mask[p] > 0.5).sort((a, b) => a - b);
const lo = skin[Math.floor(skin.length * 0.03)], hi = skin[Math.floor(skin.length * 0.97)];
const stretch = (v) => Math.max(0, Math.min(1, (v - lo) / (hi - lo)));

function render(invert) {
  const lines = [];
  for (let y = 0; y < H; y++) {
    let line = "";
    for (let x = 0; x < W; x++) {
      const p = y * W + x;
      if (mask[p] <= 0) { line += " "; continue; }
      let v = stretch(lum[p]);
      if (invert) v = 1 - v;
      // Keep every skin cell visible, and soften the mask edge
      v = (0.12 + 0.88 * v) * (0.5 + 0.5 * mask[p]);
      line += RAMP[Math.max(1, Math.min(RAMP.length - 1, Math.round(v * (RAMP.length - 1))))];
    }
    lines.push(line);
  }
  return lines;
}

// Trim empty rows (same rows for both versions so they line up)
let dark = render(false), light = render(true);
let top = 0, bottom = H;
while (top < bottom && !dark[top].trim()) top++;
while (bottom > top && !dark[bottom - 1].trim()) bottom--;
dark = dark.slice(top, bottom).map((l) => l.replace(/\s+$/, ""));
light = light.slice(top, bottom).map((l) => l.replace(/\s+$/, ""));

const asTs = (name, lines) => `export const ${name}: string[] = [\n${lines.map((l) => JSON.stringify(l)).join(",\n")},\n];\n`;
writeFileSync(
  new URL("../src/components/ascii-hands-data.ts", import.meta.url),
  `// Generated by scripts/make-ascii-hands.mjs from Michelangelo's "Creation of Adam" (public domain). Do not edit by hand.\n` +
    `export const HANDS_COLS = ${W};\n` +
    asTs("HANDS_DARK", dark) +
    asTs("HANDS_LIGHT", light)
);
console.log(`${W} x ${dark.length}`);
